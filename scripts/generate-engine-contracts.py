"""Generate JSON Schema and TypeScript from the host's public contracts."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.contracts.engine import FirmwareUploadManifest, VerificationReport, EngineToolCatalog
from backend.services.project_profile import ProjectProfile
from backend.contracts.recovery import AgentRecoveryState, EndpointHealth, RecoveryActions
from backend.contracts.diagnostics import ProviderDiagnostics
from backend.contracts.progress import TaskExecution, LinkerDiagnostic, ModelQualification


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + typescript(schema["items"]) + ">"
    if kind == "object":
        if "properties" not in schema:
            value = schema.get("additionalProperties")
            return "Record<string, " + (typescript(value) if isinstance(value, dict) else "unknown") + ">"
        required = schema.get("required", [])
        return "{\n" + "\n".join("  " + name + ("" if name in required else "?") + ": " + typescript(value) + ";"
                                   for name, value in schema["properties"].items()) + "\n}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generate():
    for directory in ("docs", "frontend/types", "frontend/lib"):
        (ROOT / directory).mkdir(parents=True, exist_ok=True)
    from backend.contracts.runtime_policy import runtime_policy_document
    policy = runtime_policy_document()
    (ROOT / "frontend/lib/runtime-policy.generated.ts").write_text(
        "// Generated by scripts/generate-engine-contracts.py. Do not edit by hand.\n"
        + "export const rendererPolicy = " + json.dumps(policy["renderer"], indent=2) + " as const;\n", encoding="utf-8")
    (ROOT / "docs/runtime-policy.generated.json").write_text(json.dumps(policy, indent=2) + "\n", encoding="utf-8")
    reference = "# ForgeX runtime defaults\n\nGenerated by scripts/generate-engine-contracts.py from host contracts.\n\n"
    reference += "| Boundary | Default seconds |\n| --- | ---: |\n"
    reference += "".join(f"| Provider {name.removesuffix('_seconds').replace('_', ' ')} | {value:g} |\n" for name, value in policy["transport"].items())
    reference += f"| Agent turn | {policy['turn_seconds']:g} |\n| Review unit | {policy['review_unit_seconds']:g} |\n"
    reference += f"| Generation turn maximum | {policy['generation_turn_seconds']:g} |\n| Model repair window | {policy['model_repair_seconds']:g} |\n"
    reference += "\nJob profiles, recovery limits, renderer defaults and failure codes: [runtime-policy.generated.json](runtime-policy.generated.json).\n\nThese are defaults. Effective phase and job deadlines can shorten an attempt. A local deadline is never a provider outage.\n"
    (ROOT / "docs/runtime-policy.generated.md").write_text(reference, encoding="utf-8")
    schemas, definitions = {}, {}
    for model in (ProjectProfile, FirmwareUploadManifest, VerificationReport, EngineToolCatalog, AgentRecoveryState, EndpointHealth, RecoveryActions, ProviderDiagnostics, TaskExecution, LinkerDiagnostic, ModelQualification):
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        schemas[model.__name__] = schema
    definitions.update(schemas)
    document = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": definitions}
    (ROOT / "docs/engine-contracts.schema.json").write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    content = "// Generated by scripts/generate-engine-contracts.py. Do not edit by hand.\n"
    content += "\n\n".join("export type " + name + " = " + typescript(schema) + ";" for name, schema in definitions.items()) + "\n"
    (ROOT / "frontend/types/engine-contracts.ts").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    generate()
